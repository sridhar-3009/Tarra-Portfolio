const ellipse = (cx, cy, rx, ry, start = -Math.PI / 2, turns = 1.05, n = 10) =>
  Array.from({ length: n + 1 }, (_, i) => {
    const a = start + (i / n) * turns * Math.PI * 2
    return [cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]
  })

